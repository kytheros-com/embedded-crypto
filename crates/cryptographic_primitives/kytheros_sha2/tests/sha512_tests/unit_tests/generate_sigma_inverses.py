"""Emit Rust inverse tables for FIPS 180-4 §4.1.3, equations (4.10)–(4.13).

A word encodes a row vector over GF(2), with bit zero at the LSB. Row i
is the image of basis vector 1 << i. For y = x A, XOR the rows of A
selected by the set bits of x. Run with python3 and assertions enabled.
"""

WIDTH = 64
IDENTITY = [1 << i for i in range(WIDTH)]
TRANSFORMS = (
    ("BIG_SIGMA_0", (28, 34, 39), None),
    ("BIG_SIGMA_1", (14, 18, 41), None),
    ("SMALL_SIGMA_0", (1, 8), 7),
    ("SMALL_SIGMA_1", (19, 61), 6),
)


def forward_rows(rotations, shift):
    """Send each basis bit to its output positions, with XOR for GF(2)."""
    rows = []
    for source in range(WIDTH):
        row = 0
        for rotation in rotations:
            row ^= 1 << ((source - rotation) % WIDTH)
        if shift is not None and source >= shift:
            row ^= 1 << (source - shift)
        rows.append(row)
    return rows


def invert(matrix):
    """Row-reduce [A | I] over GF(2). A pivot per column proves full rank."""
    left = matrix.copy()
    right = IDENTITY.copy()
    for column in range(WIDTH):
        bit = 1 << column
        pivot = next((i for i in range(column, WIDTH) if left[i] & bit), None)
        assert pivot is not None, f"missing pivot in column {column}"
        left[column], left[pivot] = left[pivot], left[column]
        right[column], right[pivot] = right[pivot], right[column]
        for row in range(WIDTH):
            if row != column and left[row] & bit:
                left[row] ^= left[column]
                right[row] ^= right[column]
    assert left == IDENTITY
    return right


def multiply(left, right):
    """Apply the right matrix to each row of the left matrix."""
    product = []
    for row in left:
        result = 0
        for i, right_row in enumerate(right):
            if row & (1 << i):
                result ^= right_row
        product.append(result)
    return product


def main():
    print("// Generated by generate_sigma_inverses.py. Rows represent basis")
    print("// images over GF(2), with bit zero at the least significant end.")
    for name, rotations, shift in TRANSFORMS:
        matrix = forward_rows(rotations, shift)
        inverse = invert(matrix)
        assert multiply(matrix, inverse) == IDENTITY, name
        assert multiply(inverse, matrix) == IDENTITY, name
        print(f"const {name}_INVERSE: [u64; 64] = [")
        for row in inverse:
            digits = f"{row:016x}"
            grouped = "_".join(digits[i:i + 4] for i in range(0, 16, 4))
            print(f"    0x{grouped},")
        print("];")


if __name__ == "__main__":
    main()
