#[test]
fn dense_boolean_bit_locality() {
    // Across these dense inputs, toggle every input position of each
    // operand in turn. Check the new output and isolate its changed bit.
    let fixtures = [
        [
            0x0123_4567_89ab_cdef,
            0xfedc_ba98_7654_3210,
            0xaaaa_aaaa_aaaa_aaaa,
        ],
        [
            0xf0e1_d2c3_b4a5_9687,
            0x1357_9bdf_2468_ace0,
            0x5555_5555_5555_5555,
        ],
    ];
    for (name, function, truth_table) in [
        ("Ch", ch as fn(u64, u64, u64) -> u64, 0xca),
        ("Maj", maj, 0xe8),
    ] {
        for words in fixtures {
            let [x, y, z] = words;
            let baseline = function(x, y, z);
            assert_eq!(baseline, boolean_oracle(words, truth_table), "{name}");
            for operand in 0..words.len() {
                for position in 0..u64::BITS {
                    let bit = 1 << position;
                    let mut changed = words;
                    changed[operand] ^= bit;
                    let [x, y, z] = changed;
                    let actual = function(x, y, z);
                    assert_eq!(
                        (actual ^ baseline) & !bit,
                        0,
                        "{name} locality, arg {operand}, bit {position}"
                    );
                    assert_eq!(
                        actual,
                        boolean_oracle(changed, truth_table),
                        "{name} flipped arg {operand}, bit {position}"
                    );
                }
            }
        }
    }
}
