//! Functional tests for FIPS 180-4 (August 2015), §4.1.3, equations
//! (4.8)–(4.13). Expected values come from local truth tables and bit
//! positions. Rotations cover each single-bit triple at every position,
//! and dense fixtures check output locality when individual bits flip.
//!
//! `generate_sigma_inverses.py` derives basis images from FIPS bit
//! destinations and uses GF(2) elimination to verify rank and both inverse
//! products. The Rust bit-position oracle works backward from output bits.
//! `verify_lfsr.py` checks that p is irreducible and that x generates the
//! multiplicative group modulo p, giving period 2^64 - 1 for every nonzero
//! state. Bit reflection preserves the period. The seed represents 1, so
//! the first 64 states represent x^0 through x^63 before modular reduction
//! is needed. These are all 64 one-hot words in descending bit order.
//!
//! The matrix and period checks establish properties of the mathematical
//! models. Rust tests exercise basis words, edge patterns, and a verified
//! prefix of 50,000 distinct states per sigma. The suite samples word-level
//! behavior and linearity. Physical fault resistance, side-channel
//! resistance, and formal algorithm validation require separate evidence.

