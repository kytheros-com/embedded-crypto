// Reflect the low coefficients of p(x) = x^64 + x^4 + x^3 + x + 1.
// Shift right and XOR the reflected mask when the old LSB is set.
// The initial state is the reflection of the polynomial residue 1.
const LFSR_MASK: u64 = 0xd800_0000_0000_0000;
const LFSR_INITIAL_STATE: u64 = 0x8000_0000_0000_0000;
const LFSR_SAMPLES: usize = 50_000;

